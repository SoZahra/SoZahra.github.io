  // Renvoie les outils d'une police : "petite", "grande" ou "titre"
  function police(nom) {
    const G = { petite: PETITE, titre: TITRE }[nom] || GRANDE;
    const HAUTEUR = G.A.length;

    // Un caractère → { lignes, dessus?, dessous? } ; inconnu → "?"
    function glyphe(car) {
      if (G[car]) return { lignes: G[car] };
      const c = COMPOSEES[car];
      if (c) {
        const base = G[c[0]];
        return c[1] === "cedille" ? { lignes: base, dessous: CEDILLE } : { lignes: base, dessus: DESSUS[c[1]] };
      }
      return { lignes: G["?"] };
    }

    function largeur(texte) {
      const cars = preparer(texte);
      return cars.reduce((s, c) => s + glyphe(c).lignes[0].length, 0) + Math.max(0, cars.length - 1) * INTERLETTRE;
    }

    // Coupe aux espaces pour ne pas dépasser largeurMax (un mot seul n'est jamais coupé).
    // Comme en typographie française, « ? ! : ; » restent collés au mot d'avant.
    function decouper(texte, largeurMax) {
      const mots = texte.trim().replace(/ +(?=[?!:;])/g, " ").split(/ +/);
      const lignes = [];
      let ligne = "";
      for (const mot of mots) {
        const essai = ligne ? `${ligne} ${mot}` : mot;
        if (ligne && largeur(essai) > largeurMax) {
          lignes.push(ligne);
          ligne = mot;
        } else {
          ligne = essai;
        }
      }
      if (ligne) lignes.push(ligne);
      return lignes;
    }

    // Le texte a-t-il des accents au-dessus / une cédille ? (place à réserver)
    function reserves(texte) {
      const g = preparer(texte).map(glyphe);
      return { dessus: g.some((x) => x.dessus), dessous: g.some((x) => x.dessous) };
    }

    // Appelle poser(x, y) pour chaque pixel creusé ; (0, 0) = haut gauche de la
    // lettre (les accents sont à y < 0, la cédille à y ≥ HAUTEUR)
    function graver(texte, poser) {
      let x = 0;
      for (const car of preparer(texte)) {
        const g = glyphe(car);
        const l = g.lignes[0].length;
        g.lignes.forEach((rang, y) => {
          for (let i = 0; i < l; i++) if (rang[i] === "#") poser(x + i, y);
        });
        const centre = x + Math.floor((l - 3) / 2);
        (g.dessus || []).forEach((rang, y) => {
          for (let i = 0; i < 3; i++) if (rang[i] === "#") poser(centre + i, y - ACCENT);
        });
        (g.dessous || []).forEach((rang, y) => {
          for (let i = 0; i < 3; i++) if (rang[i] === "#") poser(centre + i, HAUTEUR + y);
        });
        x += l + INTERLETTRE;
      }
    }

    return { HAUTEUR, ACCENT, largeur, decouper, reserves, graver };
  }

